// Facts an Analytics Agent needs to correctly *interpret* reach-campaign
// results (Lift studies, viewability, frequency) — deliberately excludes
// the per-format creative/placement specs above, which are PPC's concern
// when configuring a campaign, not Analytics's when reporting on one.
export const YANDEX_DIRECT_REACH_CAMPAIGN_ANALYTICS_FACT_KEYS: readonly string[] = [
  "yandex-direct:reach:overview",
  "yandex-direct:reach:metrics",
  "yandex-direct:reach:strategies",
];

export const YANDEX_DIRECT_REACH_CAMPAIGN_FACT_KEYS: readonly string[] =
  YANDEX_DIRECT_REACH_CAMPAIGN_FACTS.map((fact) => fact.key);

// Knowledge Base README's "Not yet implemented: initial Domain KB
// population" (Open Question #2) — this is that population, for one
// channel. `approver` states these directly (Knowledge Base §2, source 1:
// you/an expert supplying the fact yourself skips the propose→confirm
// wait), scoped to the shared `domain_kb` level so every tenant's PPC/
// Analytics Agent sees it (Memory System §3).
export function seedYandexDirectReachCampaignFacts(
  store: MemoryStore,
  approver: Actor,
  tenantId: TenantId,
): readonly ProposalResolution[] {
  return YANDEX_DIRECT_REACH_CAMPAIGN_FACTS.map((fact) =>
    recordFactDirectly(store, approver, { level: "domain_kb", tenantId, key: fact.key }, fact.value),
  );
}
